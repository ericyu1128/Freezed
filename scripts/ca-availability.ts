/**
 * npm run availability:report
 *
 * Writes docs/ca-availability.md: for every matchable catalogue item, how many
 * Canadian retailers carry it according to the hand price check
 * (data/prices.json `match`), sorted lowest first. Items no Canadian shop
 * carries are flagged when they are the top pick for any of the 864
 * questionnaire profiles the tests sweep. Deterministic: re-running on the
 * same data gives the same file.
 */

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import gearDatabase, { matchableGear } from '../lib/gearDatabase';
import { matchGear } from '../lib/matcherLogic';
import { pricesForRegion } from '../lib/pricing';
import { getRetailer, retailersForRegion } from '../lib/retailers';
import type { GearItem } from '../lib/types';
import { allProfiles } from '../lib/__tests__/profiles';
import { ROOT } from './pricesCsv';

const OUT_PATH = path.join(ROOT, 'docs', 'ca-availability.md');
const CA_SHOPS = retailersForRegion('CA');

const CATEGORY_LABEL: Record<GearItem['category'], string> = {
  skis: 'Skis',
  boots: 'Boots',
  bindings: 'Bindings',
  helmet: 'Helmet',
  goggles: 'Goggles',
  jacket: 'Jacket',
};

const categoryOf = (item: GearItem): string => {
  if (item.category === 'skis' && item.activity === 'snowboard') return 'Snowboard';
  const label = CATEGORY_LABEL[item.category];
  return (item.category === 'boots' || item.category === 'bindings') && item.activity === 'snowboard'
    ? `${label} (snowboard)`
    : label;
};

/* ---------------------------------------------------------------- */
/*  Top picks across every questionnaire profile                      */
/* ---------------------------------------------------------------- */

const profiles = allProfiles();
const topPickCount = new Map<string, number>();
for (const stats of profiles) {
  for (const rec of matchGear(stats).recommendations) {
    topPickCount.set(rec.item.id, (topPickCount.get(rec.item.id) ?? 0) + 1);
  }
}

/* ---------------------------------------------------------------- */
/*  Per-item availability                                             */
/* ---------------------------------------------------------------- */

interface Row {
  item: GearItem;
  found: string[];
  ambiguous: string[];
  checked: number;
  topPicks: number;
}

const order = new Map(matchableGear.map((item, index) => [item.id, index]));
const rows: Row[] = matchableGear
  .map((item) => {
    const prices = pricesForRegion(item, 'CA');
    const shops = (match: 'found' | 'ambiguous') =>
      prices.filter((price) => price.match === match).map((price) => getRetailer(price.retailerId).name);
    return {
      item,
      found: shops('found'),
      ambiguous: shops('ambiguous'),
      checked: prices.filter((price) => price.match !== null).length,
      topPicks: topPickCount.get(item.id) ?? 0,
    };
  })
  .sort(
    (a, b) =>
      a.found.length - b.found.length ||
      a.ambiguous.length - b.ambiguous.length ||
      b.topPicks - a.topPicks ||
      order.get(a.item.id)! - order.get(b.item.id)!,
  );

const unchecked = rows.filter((row) => row.checked < CA_SHOPS.length);
const zero = rows.filter((row) => row.found.length === 0);
const zeroTopPicks = zero.filter((row) => row.topPicks > 0);
const checkDates = Array.from(
  new Set(
    matchableGear.flatMap((item) =>
      pricesForRegion(item, 'CA').flatMap((price) => (price.checkedAt ? [price.checkedAt] : [])),
    ),
  ),
).sort();
const totalPicks = Array.from(topPickCount.values()).reduce((sum, count) => sum + count, 0);

/* ---------------------------------------------------------------- */
/*  Markdown                                                          */
/* ---------------------------------------------------------------- */

const name = (item: GearItem) => `${item.brand} ${item.name}`.replace(/\|/g, '\\|');
const list = (names: string[]) => (names.length > 0 ? names.join(', ') : '—');
const out: string[] = [];
const w = (line = '') => out.push(line);

w('# Canadian availability');
w();
w(
  `Generated by \`npm run availability:report\` from \`data/prices.json\` (price check${
    checkDates.length > 1 ? 'es' : ''
  } on ${checkDates.join(', ') || '—'}). ` +
    `For each of the ${matchableGear.length} matchable items: how many of the ${CA_SHOPS.length} Canadian ` +
    `retailers (${CA_SHOPS.map((shop) => shop.name).join(', ')}) carry it, sorted lowest first.`,
);
w();
w(
  '"Carries" means the check **found** the exact current model at a clear price. "Ambiguous" means a likely ' +
    'listing that couldn\'t be confirmed. Those shops still appear on the card as "Check price →", so they ' +
    'don\'t count as carrying it here. Details for every cell are in `docs/price-check-2026-11-04.md`.',
);
w();
w(
  `"Top pick" counts how many of the ${profiles.length} questionnaire profiles (every activity × gender × level ` +
    '× style × temperature × budget, as in the tests) get this item as their #1 for its category. ' +
    'Ranking never reads prices or availability, so these counts don\'t change when stock does.',
);
w();
w('## Summary');
w();
w(`- **${zero.length}** of ${rows.length} items are carried by no Canadian shop.`);
w(
  `- **${zeroTopPicks.length}** of those are a top pick for at least one profile ` +
    `(⚠️ below). Together they are ${zeroTopPicks.reduce((sum, row) => sum + row.topPicks, 0)} of the ` +
    `${totalPicks} top picks (profile × category).`,
);
w(
  `- ${zero.filter((row) => row.ambiguous.length === 0).length} have no found or ambiguous listing at all, so their ` +
    'card shows only the Evo Canada fallback search and "Not found at the Canadian shops we checked".',
);
if (unchecked.length > 0) {
  w(`- ${unchecked.length} item(s) were not checked at every Canadian shop: ${unchecked.map((row) => row.item.id).join(', ')}.`);
}
w();
w('## Items with zero availability that are top picks');
w();
w('| Item | Category | Top pick for (of 864) | Ambiguous at |');
w('| --- | --- | ---: | --- |');
for (const row of [...zeroTopPicks].sort((a, b) => b.topPicks - a.topPicks)) {
  w(`| ⚠️ ${name(row.item)} | ${categoryOf(row.item)} | ${row.topPicks} | ${list(row.ambiguous)} |`);
}
w();
w('## Every item, lowest availability first');
w();
w('| Item | Category | CA shops carrying it | Found at | Ambiguous at | Top pick for (of 864) |');
w('| --- | --- | ---: | --- | --- | ---: |');
for (const row of rows) {
  const flag = row.found.length === 0 && row.topPicks > 0 ? '⚠️ ' : '';
  w(
    `| ${flag}${name(row.item)} | ${categoryOf(row.item)} | ${row.found.length} of ${CA_SHOPS.length} | ` +
      `${list(row.found)} | ${list(row.ambiguous)} | ${row.topPicks} |`,
  );
}
w();
w('## Not included');
w();
w(
  'Hidden items (discontinued or nonexistent per `docs/catalogue-audit.md`) are never matched and were not ' +
    'price-checked:',
);
w();
for (const item of gearDatabase.filter((entry) => entry.hidden)) w(`- ${name(item)} (\`${item.id}\`)`);

writeFileSync(OUT_PATH, `${out.join('\n')}\n`, 'utf8');
console.log(
  `Wrote ${path.relative(ROOT, OUT_PATH)}: ${rows.length} items, ${zero.length} with zero CA availability, ` +
    `${zeroTopPicks.length} of them top picks.`,
);
